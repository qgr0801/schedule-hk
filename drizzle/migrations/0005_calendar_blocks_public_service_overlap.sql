-- When cancelled slots are not reusable, cancelled reservations also block the slot
CREATE OR REPLACE FUNCTION public.reservations_check_cancelled_slots()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NEW.status = 'cancelled' THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' AND NEW.start_at = OLD.start_at AND NEW.end_at = OLD.end_at
     AND NEW.staff_id IS NOT DISTINCT FROM OLD.staff_id AND NEW.section IS NOT DISTINCT FROM OLD.section
     AND OLD.status <> 'cancelled' THEN RETURN NEW; END IF;
  IF COALESCE((SELECT cancelled_slot_reusable FROM public.booking_settings LIMIT 1), true) THEN RETURN NEW; END IF;
  IF EXISTS (
    SELECT 1 FROM public.reservations r
    WHERE r.id <> NEW.id AND r.status = 'cancelled'
      AND tstzrange(r.start_at, r.end_at) && tstzrange(NEW.start_at, NEW.end_at)
      AND (COALESCE(r.staff_id, r.created_by) = COALESCE(NEW.staff_id, NEW.created_by)
           OR (r.section IS NOT NULL AND r.section = NEW.section))
  ) THEN
    RAISE EXCEPTION '취소된 예약의 시간대는 재사용할 수 없습니다' USING ERRCODE = '23P01';
  END IF;
  RETURN NEW;
END $$;
REVOKE EXECUTE ON FUNCTION public.reservations_check_cancelled_slots() FROM PUBLIC, anon, authenticated;
CREATE TRIGGER trg_res_cancelled_slots BEFORE INSERT OR UPDATE ON public.reservations FOR EACH ROW EXECUTE FUNCTION public.reservations_check_cancelled_slots();

-- Calendar read model: every staff sees every block; details/personal info only with permission
CREATE OR REPLACE FUNCTION public.calendar_reservations(_from timestamptz, _to timestamptz)
RETURNS TABLE (
  id uuid, created_by uuid, staff_id uuid, status public.reservation_status, section smallint, room text,
  start_at timestamptz, end_at timestamptz, public_service text, service text, category_id uuid,
  customer_name text, customer_phone text, memo text, access text
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  WITH me AS (
    SELECT auth.uid() AS uid,
           public.has_role(auth.uid(),'internal')
             AND COALESCE((SELECT s.can_view_pii FROM public.staff_view_scopes s WHERE s.user_id = auth.uid()), false) AS pii
  )
  SELECT r.id, r.created_by, r.staff_id, r.status, r.section, r.room, r.start_at, r.end_at, r.public_service,
    CASE WHEN x.d THEN r.service END,
    CASE WHEN x.d THEN c.category_id END,
    CASE WHEN x.d AND me.pii THEN r.customer_name END,
    CASE WHEN x.d AND me.pii THEN r.customer_phone END,
    CASE WHEN x.d AND me.pii THEN r.memo END,
    CASE WHEN x.d AND me.pii THEN 'pii' WHEN x.d THEN 'detail' ELSE 'block' END
  FROM public.reservations r
  CROSS JOIN me
  LEFT JOIN public.customers c ON c.id = r.customer_id
  CROSS JOIN LATERAL (SELECT public.can_view_owner(me.uid, r.created_by) AS d) x
  WHERE me.uid IS NOT NULL
    AND r.start_at >= _from AND r.start_at <= _to
    AND NOT public.can_view_full(me.uid, r.created_by)
  ORDER BY r.start_at
$$;
REVOKE EXECUTE ON FUNCTION public.calendar_reservations(timestamptz, timestamptz) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.calendar_reservations(timestamptz, timestamptz) TO authenticated;
COMMENT ON FUNCTION public.shared_reservations(timestamptz, timestamptz) IS 'DEPRECATED: replaced by calendar_reservations';

-- Live overlap warning for the booking form (block info only)
CREATE OR REPLACE FUNCTION public.find_overlaps(_start timestamptz, _end timestamptz, _staff uuid, _section smallint, _exclude uuid)
RETURNS TABLE (start_at timestamptz, end_at timestamptz, public_service text, status public.reservation_status, conflict text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT r.start_at, r.end_at, r.public_service, r.status,
    CASE WHEN COALESCE(r.staff_id, r.created_by) = _staff THEN 'staff' ELSE 'section' END
  FROM public.reservations r
  WHERE auth.uid() IS NOT NULL
    AND r.id IS DISTINCT FROM _exclude
    AND tstzrange(r.start_at, r.end_at) && tstzrange(_start, _end)
    AND (r.status <> 'cancelled' OR NOT COALESCE((SELECT b.cancelled_slot_reusable FROM public.booking_settings b LIMIT 1), true))
    AND (COALESCE(r.staff_id, r.created_by) = _staff OR (_section IS NOT NULL AND r.section = _section))
  ORDER BY r.start_at
$$;
REVOKE EXECUTE ON FUNCTION public.find_overlaps(timestamptz, timestamptz, uuid, smallint, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.find_overlaps(timestamptz, timestamptz, uuid, smallint, uuid) TO authenticated;